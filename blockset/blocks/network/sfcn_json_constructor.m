function sfcn_json_constructor(block)
	setup(block);
end

%% Function: setup ===================================================
function setup(block)
	n        = block.DialogPrm(1).Data;   %% num_signals
	buf_size = block.DialogPrm(3).Data;   %% output buffer size

	block.NumInputPorts  = n;
	block.NumOutputPorts = 2;

	%% N input ports - inherited scalar type
	for i = 1:n
		block.InputPort(i).DatatypeID        = -1;   %% inherited
		block.InputPort(i).Complexity        = 'Real';
		block.InputPort(i).Dimensions        = 1;
		block.InputPort(i).DirectFeedthrough = true;
	end

	%% Port 1 out: JSON bytes (uint8 array, length = buf_size)
	block.OutputPort(1).DatatypeID  = 3;        %% uint8
	block.OutputPort(1).Complexity  = 'Real';
	block.OutputPort(1).Dimensions  = buf_size;

	%% Port 2 out: actual JSON string length (uint16 scalar)
	block.OutputPort(2).DatatypeID  = 5;        %% uint16
	block.OutputPort(2).Complexity  = 'Real';
	block.OutputPort(2).Dimensions  = 1;

	block.NumDialogPrms = 3;
	block.SampleTimes   = [block.DialogPrm(2).Data 0];

	block.RegBlockMethod('SetInputPortDataType', @SetInpPortDType);
	block.RegBlockMethod('Outputs', @Outputs);
end

%% Called by Simulink during model update to propagate the data type into input ports.
function SetInpPortDType(block, idx, dt)
	block.InputPort(idx).DatatypeID = dt;
end

%% Simulation output - returns zeros (STM only; actual code generated by TLC).
function Outputs(block)
	buf_size = block.DialogPrm(3).Data;
	block.OutputPort(1).Data = zeros(buf_size, 1, 'uint8');
	block.OutputPort(2).Data = uint16(0);
end

